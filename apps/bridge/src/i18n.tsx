export type TranslationKey = keyof typeof messages['zh-CN'];

type I18nValue = {
  locale: Locale;
  setLocale(locale: Locale): void;
  t(key: TranslationKey, values?: Readonly<Record<string, string | number>>): string;
};

const defaultValue: I18nValue = {
  locale: 'en',
  setLocale: () => undefined,
  t(key, values = {}) {
    let output: string = messages.en[key];
    for (const [name, replacement] of Object.entries(values)) {
      output = output.replaceAll(`{${name}}`, String(replacement));
    }
    return output;
  },
};

const I18nContext = createContext<I18nValue>(defaultValue);

function initialLocale(): Locale {
  try {
    return window.localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'zh-CN';
  } catch {
    return 'zh-CN';
  }
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale(nextLocale) {
      setLocaleState(nextLocale);
      try {
        window.localStorage.setItem(STORAGE_KEY, nextLocale);
      } catch {
        // A blocked storage API must not prevent an in-memory language change.
      }
    },
    t(key, values = {}) {
      let output: string = messages[locale][key];
      for (const [name, replacement] of Object.entries(values)) {
        output = output.replaceAll(`{${name}}`, String(replacement));
      }
      return output;
    },
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
